AssetBuildResult buildDeclaredAsset(const QString &pimPath, const AssetBuildRequest &request,
                                    const QString &buildDirectory)
{
    AssetBuildResult result;
    if (!singleFileName(request.outputFileName)) {
        result.error = QObject::tr("The output name must be a single file name, such as hero.dat.");
        return result;
    }
    if (request.phaseName.isEmpty()) {
        result.error = QObject::tr("A sprite export needs a phase name.");
        return result;
    }

    QFile input(pimPath);
    if (!input.open(QIODevice::ReadOnly)) {
        result.error = QObject::tr("cannot read '%1': %2").arg(pimPath, input.errorString());
        return result;
    }
    const QByteArray document = input.readAll();
    if (input.error() != QFile::NoError) {
        result.error = QObject::tr("cannot read '%1': %2").arg(pimPath, input.errorString());
        return result;
    }

    const QString baseName = QFileInfo(request.outputFileName).completeBaseName();
    result.dataPath = QDir(buildDirectory).filePath(request.outputFileName);
    result.includePath = QDir(buildDirectory).filePath(baseName + QStringLiteral(".i"));
    const QString stampPath = QDir(buildDirectory).filePath(request.outputFileName + QStringLiteral(".stamp"));
    const QByteArray stamp = stampFor(document, request);

    if (QFileInfo::exists(result.dataPath) && QFileInfo::exists(result.includePath)
        && QFileInfo::exists(stampPath)) {
        QFile stampFile(stampPath);
        if (stampFile.open(QIODevice::ReadOnly) && stampFile.readAll().trimmed() == stamp) {
            result.ok = true;
            result.unchanged = true;
            return result;
        }
    }

    ImageDocument doc;
    QString error;
    if (!doc.fromJson(document, &error)) {
        result.error = error.isEmpty() ? QObject::tr("'%1' is not a sprite document.").arg(pimPath) : error;
        return result;
    }
    int phase = -1;
    QStringList names;
    for (int i = 0; i < doc.phaseCount(); ++i) {
        names.append(doc.phases().at(i).name);
        if (phase < 0 && doc.phases().at(i).name == request.phaseName)
            phase = i;
    }
    if (phase < 0) {
        result.error = QObject::tr("'%1' has no phase \"%2\". It has: %3.")
                           .arg(QFileInfo(pimPath).fileName(), request.phaseName,
                                names.isEmpty() ? QObject::tr("(none)") : names.join(QStringLiteral(", ")));
        return result;
    }

    const QByteArray bytes = exportBitplaneData(doc, phase, request.options, &error);
    if (bytes.isEmpty()) {
        result.error = error;
        return result;
    }
    const ImagePhase &chosen = doc.phases().at(phase);
    const QVector<BitplaneBlock> blocks =
        bitplaneLayout(chosen.cellW, chosen.cellH, chosen.frames.size(), request.options);
    const QString include =
        includeText(pimPath, request.phaseName, request.outputFileName, symbolFromFileName(request.outputFileName),
                    blocks, chosen.frames.size(), int(bytes.size()));

    if (!QDir().mkpath(buildDirectory)) {
        result.error = QObject::tr("cannot create '%1'").arg(buildDirectory);
        return result;
    }

    bool hadData = false;
    bool hadInclude = false;
    QByteArray oldData;
    QByteArray oldInclude;
    if (!readExisting(result.dataPath, &hadData, &oldData, &result.error)
        || !readExisting(result.includePath, &hadInclude, &oldInclude, &result.error))
        return result;

    if (!files::write(result.dataPath, bytes, &result.error))
        return result;
    if (!files::write(result.includePath, include.toUtf8(), &result.error)) {
        QString restoreError;
        restore(result.dataPath, hadData, oldData, &restoreError);
        return result;
    }
    if (!files::write(stampPath, stamp + '\n', &result.error)) {
        // The bytes are the ones this build will assemble. A missing stamp
        // only means the next build writes them again.
        result.error.clear();
    }
    result.ok = true;
    return result;
}

