bool singleFileName(const QString &name)
{
    if (name.isEmpty() || name == QLatin1String(".") || name == QLatin1String(".."))
        return false;
    if (name.contains(QLatin1Char('/')) || name.contains(QLatin1Char('\\')))
        return false;
    return QFileInfo(name).fileName() == name;
}

QString symbolFromFileName(const QString &fileName)
{
    QString base = QFileInfo(fileName).completeBaseName();
    QString symbol;
    for (const QChar ch : base) {
        if (ch.isLetterOrNumber() || ch == QLatin1Char('_'))
            symbol.append(ch);
        else
            symbol.append(QLatin1Char('_'));
    }
    if (symbol.isEmpty())
        symbol = QStringLiteral("asset");
    if (symbol.at(0).isDigit())
        symbol.prepend(QLatin1Char('_'));
    return symbol;
}

QByteArray stampFor(const QByteArray &document, const AssetBuildRequest &request)
{
    QCryptographicHash hash(QCryptographicHash::Sha256);
    hash.addData("pist-asset-1");
    hash.addData(document);
    hash.addData(request.phaseName.toUtf8());
    hash.addData(request.outputFileName.toUtf8());
    const BitplaneDataOptions &opt = request.options;
    const QByteArray flags = QByteArray::number(int(opt.palette)) + ','
                             + QByteArray::number(int(opt.sprite)) + ','
                             + QByteArray::number(int(opt.masked)) + ','
                             + QByteArray::number(int(opt.shifted)) + ','
                             + QByteArray::number(int(opt.shiftedMasked)) + ','
                             + QByteArray::number(opt.preShifts) + ','
                             + QByteArray::number(opt.transparent);
    hash.addData(flags);
    return hash.result().toHex();
}

bool readExisting(const QString &path, bool *existed, QByteArray *bytes, QString *error)
{
    *existed = QFileInfo::exists(path);
    bytes->clear();
    if (!*existed)
        return true;
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly)) {
        if (error)
            *error = QObject::tr("cannot read '%1': %2").arg(path, file.errorString());
        return false;
    }
    *bytes = file.readAll();
    if (file.error() != QFile::NoError) {
        if (error)
            *error = QObject::tr("cannot read '%1': %2").arg(path, file.errorString());
        return false;
    }
    return true;
}

bool restore(const QString &path, bool existed, const QByteArray &bytes, QString *error)
{
    if (!existed) {
        QFile::remove(path);
        return true;
    }
    return files::write(path, bytes, error);
}

QString equLine(const QString &name, int value)
{
    return name + QStringLiteral("\t\tequ\t") + QString::number(value) + QLatin1Char('\n');
}

QString includeText(const QString &pimPath, const QString &phaseName, const QString &dataFileName,
                    const QString &symbol, const QVector<BitplaneBlock> &blocks, int frames,
                    int totalBytes)
{
    int frameStride = 0;
    int frame0 = -1;
    int frame1 = -1;
    int palette = -1;
    for (const BitplaneBlock &block : blocks) {
        if (block.kind == BitplaneBlock::Kind::Palette)
            palette = block.offset;
        if (block.frame == 0 && frame0 < 0)
            frame0 = block.offset;
        if (block.frame == 1 && frame1 < 0)
            frame1 = block.offset;
    }
    if (frame0 >= 0 && frame1 > frame0)
        frameStride = frame1 - frame0;
    else if (frame0 >= 0) {
        for (const BitplaneBlock &block : blocks) {
            if (block.frame == 0)
                frameStride += block.bytes;
        }
    }

    const QString prefix = symbol.toUpper();
    QString phase = phaseName;
    phase.replace(QLatin1Char('\n'), QLatin1Char(' '));
    QString text;
    text += QStringLiteral("; Generated by PiST from %1, phase \"%2\".\n")
                .arg(QFileInfo(pimPath).fileName(), phase);
    text += QStringLiteral("; Do not edit. The next build rewrites this file.\n");
    text += symbol + QStringLiteral(":\n");
    text += QStringLiteral("\tincbin\t\"%1\"\n").arg(dataFileName);
    text += equLine(prefix + QStringLiteral("_BYTES"), totalBytes);
    text += equLine(prefix + QStringLiteral("_FRAMES"), frames);
    text += equLine(prefix + QStringLiteral("_FRAME_STRIDE"), frameStride);
    if (palette >= 0)
        text += equLine(prefix + QStringLiteral("_PALETTE"), palette);
    return text;
}

